"""Write driver/ddr/ddr_tables.c from the vendor AX620U first stage.

    gen_ddr_tables.py <flash dump or first stage code> <out.c>

The DDR controller, PI and PHY settings of the vendor first stage are
data: tables of register/value pairs and bit fields its init code
writes in order (0xe300-0x125fc when the code runs at 0x800) and four
board configuration words after them. This copies them out as C. Given
a whole flash image, the code is found at 0x800 behind the two headers.
"""
import struct
import sys

BASE = 0x800

PAIRS = [  # name, address, entries: {reg, val}
    ('ddr_ctl_regs', 0xe300, 0x179),
    ('ddr_phy_regs', 0x1042c, 0x2ad),
    ('ddr_phy_board_regs', 0x121ec, 0x5d),
    ('ddr_ctl_timing_regs', 0x12544, 0x17),
    ('ddr_pi_timing_regs', 0x124d4, 0xe),
]
WORDS = [('ddr_pi_regs', 0xeec8, 0x559)]  # PI registers 0..0x558
FIELDS = [  # name, address, entries: {reg, val, width, shift}
    ('ddr_phy_fields', 0x11b8c, 0x16),
    ('ddr_phy_fields_cfg100', 0x11c94, 0x72),
    ('ddr_phy_fields_mode2', 0x11b2c, 4),
    ('ddr_phy_fields_mode0', 0x11b5c, 4),
    ('ddr_phy_fields_mode3', 0x11994, 0x16),
    ('ddr_phy_fields_mode1', 0x11a9c, 0xc),
]
CFG = [('ddr_cfg_dq_drv', 0x125fc), ('ddr_cfg_dpll', 0x12600),
       ('ddr_cfg_phy', 0x12604), ('ddr_cfg', 0x12608)]


def main():
    d = open(sys.argv[1], 'rb').read()
    if d[4:8] == b'\x22\x33\x54\x55':
        d = d[0x800:]
    w = lambda a: struct.unpack_from('<I', d, a - BASE)[0]
    out = ['// SPDX-License-Identifier: GPL-2.0+',
           '/* Generated by tools/gen_ddr_tables.py from the vendor first stage. */',
           '#include "cmn.h"', '#include "ddr_tables.h"', '']
    for name, a, n in PAIRS:
        out.append(f'const struct ddr_reg_val {name}[{n:#x}] = {{')
        out += [f'\t{{ {w(a + 8 * i):#010x}, {w(a + 8 * i + 4):#010x} }},' for i in range(n)]
        out += ['};', '']
    for name, a, n in WORDS:
        out.append(f'const u32 {name}[{n:#x}] = {{')
        for i in range(0, n, 4):
            out.append('\t' + ' '.join(f'{w(a + 4 * j):#010x},' for j in range(i, min(i + 4, n))))
        out += ['};', '']
    for name, a, n in FIELDS:
        out.append(f'const struct ddr_reg_field {name}[{n:#x}] = {{')
        for i in range(n):
            e = a + 12 * i
            out.append(f'\t{{ {w(e):#010x}, {w(e + 4):#x}, {d[e + 8 - BASE]}, {d[e + 9 - BASE]} }},')
        out += ['};', '']
    for name, a in CFG:
        out.append(f'const u32 {name} = {w(a):#x};')
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
