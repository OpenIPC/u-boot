#!/usr/bin/env python3
"""
Turn regdump logs (one per output timing) into a C header for U-Boot: one
register program shared by every mode, the values that differ per mode in a
table, delays kept.

  gen-tables.py out.h 1080p60.log 720p60.log ...

Left out on purpose:
  - reads (the HAL's read-modify-writes are kept as masked writes);
  - the "port" section (the MOP window: U-Boot programs it per picture);
  - the HDMI TX analog trims, ATOP 0x19/0x1A/0x38: the IPL has already
    written each chip's efuse values there, the HAL would put defaults back.

SPDX-License-Identifier: GPL-2.0+
"""
import os
import sys

DIMS = {"1080p60": (1920, 1080), "1080p50": (1920, 1080),
        "720p60": (1280, 720), "720p50": (1280, 720),
        "1024x768": (1024, 768), "1280x1024": (1280, 1024),
        "1440x900": (1440, 900)}
SKIP = {("1126", "19"), ("1126", "1a"), ("1126", "38")}
SECTIONS_OUT = {"port"}


def load(path):
    ops = []
    sec = None
    for line in open(path):
        p = line.split()
        if not p:
            continue
        if p[0] == "#":
            sec = p[1]
            continue
        if sec in SECTIONS_OUT or p[0] == "R":
            continue
        if p[0] == "D":
            ops.append(("D", None, None, int(p[1]), 0))
            continue
        bank, reg = p[1], p[2]
        if (bank, reg) in SKIP:
            continue
        val = int(p[3], 16)
        mask = int(p[4], 16) if p[0] == "M" else 0xFFFF
        ops.append(("W", bank, reg, val, mask))
    return ops


def main():
    out, logs = sys.argv[1], sys.argv[2:]
    modes = [os.path.basename(l).rsplit(".", 1)[0] for l in logs]
    progs = [load(l) for l in logs]
    n = len(progs[0])
    for m, p in zip(modes, progs):
        sig = [(o[0], o[1], o[2], o[4]) for o in p]
        if sig != [(o[0], o[1], o[2], o[4]) for o in progs[0]]:
            sys.exit(f"{m}: not the same register sequence as {modes[0]}")

    # drop writes that repeat the previous op exactly (same everywhere)
    keep = [i for i in range(n)
            if not (i and all(p[i] == p[i - 1] for p in progs)
                    and progs[0][i][0] == "W")]

    lines, var_rows = [], [[] for _ in modes]
    delay = 0
    for i in keep:
        kind, bank, reg, val, mask = progs[0][i]
        vals = [p[i][3] for p in progs]
        if kind == "D":
            lines.append(f"\tMS_DISP_DELAY({val}),")
            delay += val
            continue
        if len(set(vals)) == 1:
            lines.append(f"\tMS_DISP_W(0x{bank}, 0x{reg}, 0x{mask:04x}, 0x{val:04x}),")
        else:
            idx = len(var_rows[0])
            for r, v in zip(var_rows, vals):
                r.append(v)
            lines.append(f"\tMS_DISP_V(0x{bank}, 0x{reg}, 0x{mask:04x}, {idx}),")

    with open(out, "w") as f:
        f.write("/* SPDX-License-Identifier: GPL-2.0+ */\n"
                "/*\n * Generated by openipc/tools/disp-regdump/gen-tables.py:"
                " the register program\n * SigmaStar's infinity2m display +"
                " HDMI TX drivers (boot_621_release,\n * cmd_bootlogo.c's HDMI"
                " path, HDMI and VGA) write for each output mode.\n"
                f" * {len(lines)} operations, {delay // 1000} ms of delays.\n */\n\n")
        f.write("static const struct ms_disp_op ms_disp_prog[] = {\n")
        f.write("\n".join(lines) + "\n};\n\n")
        f.write("static const struct ms_disp_mode ms_disp_modes[] = {\n")
        for m in modes:
            w, h = DIMS[m]
            f.write(f'\t{{ "{m}", {w}, {h} }},\n')
        f.write("};\n\n")
        nv = len(var_rows[0])
        f.write(f"static const u16 ms_disp_vars[][{nv}] = {{\n")
        for m, r in zip(modes, var_rows):
            body = ", ".join(f"0x{v:04x}" for v in r)
            f.write(f"\t/* {m} */\n\t{{ {body} }},\n")
        f.write("};\n")
    print(f"{out}: {len(lines)} ops, {nv} per-mode values, "
          f"{delay // 1000} ms delays, modes {', '.join(modes)}")


if __name__ == "__main__":
    main()
