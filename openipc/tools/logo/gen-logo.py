#!/usr/bin/env python3
"""Turn the OpenIPC logo (openipc-logo-white.svg, from OpenIPC/.github)
into drivers/video/sigmastar/ms_logo_paths.h: its outlines as a stream of
path commands that ms_logo.c fills at any output size.

   gen-logo.py openipc-logo-white.svg > ms_logo_paths.h

Only what this SVG uses is understood: one <g> with a matrix transform,
<path> elements with M/m L/l H/h V/v C/c Z/z, filled nonzero.
Coordinates are stored in 1/64 of a viewBox unit, as int16.
"""
import re
import sys
import xml.etree.ElementTree as ET

SCALE = 64
OP_END, OP_MOVE, OP_LINE, OP_CUBIC, OP_CLOSE = 0, 1, 2, 3, 4


def tokens(d):
    for m in re.finditer(r"[MmLlHhVvCcZz]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?", d):
        yield m.group(0)


def parse(d):
    """Absolute subpaths: lists of ('M'|'L'|'C'|'Z', points)."""
    out, cmd, x, y, sx, sy = [], None, 0.0, 0.0, 0.0, 0.0
    toks = list(tokens(d))
    i = 0

    def num():
        nonlocal i
        i += 1
        return float(toks[i - 1])

    while i < len(toks):
        if toks[i].isalpha():
            cmd = toks[i]
            i += 1
            if cmd in "Zz":
                out.append(("Z", []))
                x, y = sx, sy
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            sx, sy = x, y
            out.append(("M", [(x, y)]))
            cmd = "l" if rel else "L"           # further pairs are lines
        elif c == "L":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            out.append(("L", [(x, y)]))
        elif c == "H":
            n = num()
            x = x + n if rel else n
            out.append(("L", [(x, y)]))
        elif c == "V":
            n = num()
            y = y + n if rel else n
            out.append(("L", [(x, y)]))
        elif c == "C":
            p = [num() for _ in range(6)]
            if rel:
                p = [p[k] + (x if k % 2 == 0 else y) for k in range(6)]
            out.append(("C", [(p[0], p[1]), (p[2], p[3]), (p[4], p[5])]))
            x, y = p[4], p[5]
        else:
            raise SystemExit("unsupported path command " + cmd)
    return out


def main():
    root = ET.parse(sys.argv[1]).getroot()
    ns = {"s": "http://www.w3.org/2000/svg"}
    vb = [float(v) for v in root.get("viewBox").split()]
    g = root.find("s:g", ns)
    a, b, c, d, e, f = [float(v) for v in
                        re.search(r"matrix\(([^)]*)\)", g.get("transform")).group(1).split(",")]
    stream = []
    for p in g.findall("s:path", ns):
        for op, pts in parse(p.get("d")):
            stream.append({"M": OP_MOVE, "L": OP_LINE, "C": OP_CUBIC, "Z": OP_CLOSE}[op])
            for px, py in pts:
                tx, ty = a * px + c * py + e, b * px + d * py + f
                stream += [round(tx * SCALE), round(ty * SCALE)]
    stream.append(OP_END)
    assert all(-32768 <= v < 32768 for v in stream)
    print("/* SPDX-License-Identifier: GPL-2.0+ */")
    print("/* Generated by openipc/tools/logo/gen-logo.py from")
    print(" * openipc-logo-white.svg: the OpenIPC logo's outlines, in 1/%d" % SCALE)
    print(" * of its %gx%g viewBox. Do not edit. */" % (vb[2], vb[3]))
    print("#define MS_LOGO_W\t%d\t/* viewBox, units */" % vb[2])
    print("#define MS_LOGO_H\t%d" % vb[3])
    print("#define MS_LOGO_SCALE\t%d" % SCALE)
    print("enum { LOGO_END, LOGO_MOVE, LOGO_LINE, LOGO_CUBIC, LOGO_CLOSE };")
    print("static const s16 ms_logo_path[] = {")
    for k in range(0, len(stream), 12):
        print("\t" + ", ".join(str(v) for v in stream[k:k + 12]) + ",")
    print("};")


if __name__ == "__main__":
    main()
