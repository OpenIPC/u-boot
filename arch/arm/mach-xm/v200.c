/*
 * After the bring-up the XM535 builds write and read back two patterns at
 * the start of DRAM, and reset the SoC if either does not stick. Done here
 * for all three: a failed bring-up then retries rather than hangs later.
 */
static bool ddr_holds(u32 a, u32 b)
{
	writel(a, XM_DDR_BASE);
	writel(b, XM_DDR_BASE + 4);
	return readl(XM_DDR_BASE) == a && readl(XM_DDR_BASE + 4) == b;
}

/* writel/readl, so every compare is a bus read the compiler cannot fold */
static void ddr_check(void)
{
	if (ddr_holds(0xaaaa5555, 0x74de0ee3) && ddr_holds(0x5555aaaa, 0x8b21f11c))
		return;
	xm_soc_reset();
}

void xm_ddr_init(void)
{
	const struct ddr_step *s;

	for (s = ddr_program; s < ddr_program + ARRAY_SIZE(ddr_program); s++) {
		switch (s->op) {
		case OP_W:
			writel(s->val, s->reg);
			break;
		case OP_OR:
			writel(readl(s->reg) | s->val, s->reg);
			break;
		case OP_BIC:
			writel(readl(s->reg) & ~s->val, s->reg);
			break;
		case OP_POLL_EQ:
			while (readl(s->reg) != s->val)
				;
			break;
		case OP_POLL_SET:
			wait_set(s->reg, s->val);
			break;
		case OP_DELAY:
			xm_early_udelay(s->val);
			break;
		}
	}
	ddr_check();
}
